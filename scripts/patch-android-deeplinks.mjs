#!/usr/bin/env node
/**
 * Patches android/app/src/main/AndroidManifest.xml with App Links + custom scheme
 * from clients/<id>/config.json. Safe to re-run (idempotent via marker comments).
 *
 * Usage: CLIENT=simy node scripts/patch-android-deeplinks.mjs
 */

import { readFileSync, writeFileSync, existsSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')

const clientId = process.env.CLIENT || process.argv[2] || 'simy'
const configPath = join(root, `clients/${clientId}/config.json`)
const manifestPath = join(root, 'android/app/src/main/AndroidManifest.xml')

if (!existsSync(configPath)) {
  console.error(`❌ Config not found: ${configPath}`)
  process.exit(1)
}
if (!existsSync(manifestPath)) {
  console.error(`❌ Manifest not found: ${manifestPath}`)
  process.exit(1)
}

const client = JSON.parse(readFileSync(configPath, 'utf-8'))
const scheme = client.scheme || clientId
const host = (() => {
  try {
    return new URL(client.serverUrl || 'https://app.simy.ch').hostname
  } catch {
    return 'app.simy.ch'
  }
})()

const START = '<!-- DEEPLINKS:START (generated by scripts/patch-android-deeplinks.mjs) -->'
const END = '<!-- DEEPLINKS:END -->'

const block = `            ${START}
            <!-- HTTPS App Links (autoVerify → assetlinks.json) -->
            <intent-filter android:autoVerify="true">
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="https" android:host="${host}" android:pathPrefix="/payment-callback" />
                <data android:scheme="https" android:host="${host}" android:pathPrefix="/customer-dashboard" />
                <data android:scheme="https" android:host="${host}" android:pathPrefix="/login" />
            </intent-filter>

            <!-- Custom URL scheme fallback -->
            <intent-filter>
                <action android:name="android.intent.action.VIEW" />
                <category android:name="android.intent.category.DEFAULT" />
                <category android:name="android.intent.category.BROWSABLE" />
                <data android:scheme="${scheme}" />
            </intent-filter>
            ${END}`

let manifest = readFileSync(manifestPath, 'utf-8')

// Remove previous generated block if present
if (manifest.includes(START) && manifest.includes(END)) {
  manifest = manifest.replace(
    new RegExp(`[ \\t]*${escapeRegex(START)}[\\s\\S]*?${escapeRegex(END)}\\n?`),
    '',
  )
}

// Insert after the LAUNCHER intent-filter's closing tag inside MainActivity
const launcherClose = `            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>`

if (!manifest.includes(launcherClose)) {
  console.error('❌ Could not find LAUNCHER intent-filter in AndroidManifest.xml')
  process.exit(1)
}

manifest = manifest.replace(launcherClose, `${launcherClose}\n\n${block}`)

writeFileSync(manifestPath, manifest)
console.log(`✅ Android deeplinks patched for ${clientId}`)
console.log(`   host:   https://${host}`)
console.log(`   scheme: ${scheme}://`)
console.log(`   paths:  /payment-callback, /customer-dashboard, /login`)

function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}
